const fs = require('fs');
const path = require('path');
const {
  atomicWrite, dateString, isFinalized, planRecord, readRecords, readState,
  utcTimestamp, validateClassifications,
} = require('./contribution-sync');

function parseOptions(args) {
  const options = { force: false, dryRun: false, report: '.cache/contribution-sync/report.json' };
  for (let index = 0; index < args.length; index++) {
    const arg = args[index];
    if (arg === '--force') options.force = true;
    else if (arg === '--dry-run') options.dryRun = true;
    else if (arg === '--help') options.help = true;
    else if (['--report', '--classification-file'].includes(arg)) {
      const value = args[++index];
      if (!value || value.startsWith('--')) throw new Error(`${arg} requires a filename`);
      options[arg === '--report' ? 'report' : 'classificationFile'] = value;
    } else throw new Error(`Unknown option: ${arg}`);
  }
  if (options.classificationFile && !options.force) throw new Error('--classification-file requires --force');
  return options;
}

async function fetchJson(url, gerrit = false) {
  // Only public endpoints are used; no credential or environment lookup.
  const response = await fetch(url, { headers: { Accept: 'application/json' }, signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`Public source returned HTTP ${response.status}`);
  const text = await response.text();
  return JSON.parse(gerrit ? text.replace(/^\)\]\}'\r?\n/, '') : text);
}

async function fetchGerrit(records) {
  const result = new Map();
  for (let offset = 0; offset < records.length; offset += 30) {
    const group = records.slice(offset, offset + 30);
    const url = new URL('https://chromium-review.googlesource.com/changes/');
    url.searchParams.set('q', group.map(record => `change:${record.source.id}`).join(' OR '));
    url.searchParams.set('n', '100');
    for (const option of ['MESSAGES', 'CURRENT_REVISION', 'CURRENT_FILES']) url.searchParams.append('o', option);
    const changes = await fetchJson(url, true);
    if (!Array.isArray(changes) || changes.some(change => change._more_changes)) throw new Error('Incomplete Gerrit query result');
    for (const record of group) {
      const matches = changes.filter(change => change._number === record.source.id);
      if (matches.length !== 1) throw new Error(`${record.slug}: Gerrit source is missing or ambiguous`);
      const change = matches[0];
      if (record.data.repo && record.data.repo !== change.project) throw new Error(`${record.slug}: Gerrit project differs from repo`);
      const abandoned = (change.messages || []).filter(message => message.tag === 'autogenerated:gerrit:abandon')
        .map(message => utcTimestamp(message.date)).sort().at(-1);
      result.set(record.slug, {
        status: { NEW: 'in review', MERGED: 'merged', ABANDONED: 'abandoned' }[change.status],
        createdAt: change.created, updatedAt: change.updated,
        resolvedAt: change.status === 'MERGED' ? change.submitted : change.status === 'ABANDONED' ? abandoned : undefined,
        revision: change.current_revision, project: change.project, subject: change.subject,
        files: Object.keys(change.revisions?.[change.current_revision]?.files || {}),
      });
    }
    console.log(`Checked Gerrit ${Math.min(offset + 30, records.length)}/${records.length}`);
  }
  return result;
}

async function fetchGithub(record) {
  const root = `https://api.github.com/repos/${record.source.repo}/pulls/${record.source.id}`;
  const pull = await fetchJson(root);
  if (pull.number !== record.source.id || pull.base?.repo?.full_name?.toLowerCase() !== record.source.repo.toLowerCase()) {
    throw new Error(`${record.slug}: GitHub PR source identity differs`);
  }
  const files = [];
  if (!Number.isInteger(pull.changed_files) || pull.changed_files < 0 || pull.changed_files > 3000) {
    throw new Error(`${record.slug}: GitHub file count is invalid or exceeds the API limit`);
  }
  for (let page = 1; page <= Math.max(1, Math.ceil(pull.changed_files / 100)); page++) {
    const batch = await fetchJson(`${root}/files?per_page=100&page=${page}`);
    if (!Array.isArray(batch)) throw new Error('Invalid GitHub file list');
    files.push(...batch.map(file => file.filename));
  }
  if (files.length !== pull.changed_files) throw new Error(`${record.slug}: GitHub file list is incomplete`);
  return {
    status: pull.merged ? 'merged' : pull.state === 'closed' ? 'abandoned' : 'in review',
    createdAt: pull.created_at, updatedAt: pull.updated_at,
    resolvedAt: pull.merged ? pull.merged_at : pull.closed_at,
    revision: pull.head.sha, project: record.source.repo, subject: pull.title, files,
  };
}

async function main() {
  const options = parseOptions(process.argv.slice(2));
  if (options.help) {
    console.log(`Usage: npm run sync:contributions -- [options]
  --dry-run                  Report without changing records or sync state
  --force                    Recheck all records, including finalized Merged
  --classification-file FILE Apply skill-reviewed module/kind decisions (force)
  --report FILE              Report path (default .cache/contribution-sync/report.json)
  --help                     Show usage

The script updates exact source dates/status. The skill reviews classification.
No tokens are read; public Gerrit and GitHub endpoints are used.`);
    return;
  }
  const directory = path.resolve('data/contributions');
  const stateFile = path.resolve('data/maintenance/contribution-sync.json');
  const reportFile = path.resolve(options.report);
  if (reportFile === stateFile || reportFile.startsWith(directory + path.sep)) throw new Error('Report must be outside contribution records and sync state');
  if (options.classificationFile && reportFile === path.resolve(options.classificationFile)) throw new Error('Report must differ from the classification input');
  if (fs.existsSync(reportFile) && JSON.parse(fs.readFileSync(reportFile, 'utf8')).type !== 'contribution-sync-report') {
    throw new Error('Report would overwrite a file that is not a contribution sync report');
  }
  const records = readRecords(directory, options.force);
  const stateRaw = fs.existsSync(stateFile) ? fs.readFileSync(stateFile, 'utf8') : null;
  const state = readState(stateFile);
  const classifications = validateClassifications(options.classificationFile ? JSON.parse(fs.readFileSync(options.classificationFile, 'utf8')) : {}, records);
  const selected = records.filter(record => options.force || !isFinalized(record, state));
  const snapshots = await fetchGerrit(selected.filter(record => record.source.type === 'gerrit'));
  for (const record of selected.filter(record => record.source.type === 'github')) snapshots.set(record.slug, await fetchGithub(record));
  const verifiedAt = new Date().toISOString();
  const plans = selected.map(record => planRecord(record, snapshots.get(record.slug), classifications[record.slug], verifiedAt, options.force && options.dryRun));
  const report = {
    type: 'contribution-sync-report', checkedAt: verifiedAt, force: options.force, dryRun: options.dryRun,
    summary: {
      total: records.length, checked: selected.length,
      skippedFinalized: records.length - selected.length,
      changed: plans.filter(plan => Object.keys(plan.changes).length).length,
      finalized: plans.filter(plan => plan.state.finalized).length,
      classifications: Object.keys(classifications).length,
      needsClassification: plans.filter(plan => plan.needsClassification).length,
    },
    records: plans.map(plan => ({
      slug: plan.record.slug, path: path.relative(process.cwd(), plan.record.filename),
      sourceUrl: plan.record.source.url,
      current: Object.fromEntries(['date', 'resolvedDate', 'status', 'module', 'kind'].map(key => [key, dateString(plan.record.data[key]) ?? null])),
      source: snapshots.get(plan.record.slug), changes: plan.changes, needsClassification: plan.needsClassification,
    })),
    skippedFinalized: records.filter(record => !options.force && isFinalized(record, state)).map(record => record.slug),
  };
  atomicWrite(reportFile, JSON.stringify(report, null, 2) + '\n');
  if (!options.dryRun) {
    // Detect concurrent edits before writing anything; failed runs retain old flags.
    if ((fs.existsSync(stateFile) ? fs.readFileSync(stateFile, 'utf8') : null) !== stateRaw ||
        plans.some(plan => fs.readFileSync(plan.record.filename, 'utf8') !== plan.record.raw)) {
      throw new Error('Records or sync state changed during collection; rerun the command');
    }
    for (const plan of plans) if (plan.raw !== plan.record.raw) atomicWrite(plan.record.filename, plan.raw);
    for (const plan of plans) state.records[plan.record.slug] = plan.state;
    if (plans.length) atomicWrite(stateFile, JSON.stringify(state, null, 2) + '\n');
  }
  console.log(JSON.stringify(report.summary));
  console.log(`${options.dryRun ? 'Preview' : 'Applied'}; report: ${path.relative(process.cwd(), reportFile)}`);
}

main().catch(error => { console.error(`Contribution sync failed: ${error.message}`); process.exitCode = 1; });
